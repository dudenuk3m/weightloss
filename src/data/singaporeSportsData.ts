// Helper to calculate calorie burn for any weight and duration
export function calculateSportCalories(sport: SingaporeSport, weightKg: number, minutes: number): number {
  // Calorie formula: (MET * 3.5 * weightKg / 200) * minutes
  const calories = (sport.mets * 3.5 * weightKg / 200) * minutes;
  return Math.round(calories);
}

// Calculate grams of pure fat tissue burned (approx 7,700 kcal per kg of human body fat)
export function calculateFatLossGrams(caloriesBurned: number): number {
  return parseFloat(((caloriesBurned / 7700) * 1000).toFixed(1));
}
